#!/usr/bin/env node
/* global console */
/**
 * Renders ROLE_PERMISSIONS_DERIVATION.md from the transcribed matrix.
 *
 * KF-S0-API-003. The handover asks for "the same reviewable artifact
 * CONTRACT-001 produced: a derivation table from matrix cell → seeded row".
 * Rendering it rather than hand-writing it means the table and the seed cannot
 * disagree — they read the same source — and the contracts test asserts the
 * committed file is current.
 *
 * Usage:  node apps/api/prisma/seed-data/render-derivation.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { ALL_PERMISSIONS } from '@kf/contracts';

import { MATRIX, ROLE_CODES, derivePairs } from './role-permission-matrix.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, 'ROLE_PERMISSIONS_DERIVATION.md');

function render() {
  const { pairs, unmapped } = derivePairs(ALL_PERMISSIONS);

  const granted = new Set(pairs.map((p) => p.code));
  const ungranted = ALL_PERMISSIONS.filter((c) => !granted.has(c));

  const perRole = ROLE_CODES.map((role) => ({
    role,
    count: pairs.filter((p) => p.role === role).length,
  }));

  const lines = [];
  const w = (s = '') => lines.push(s);

  w('# `role_permissions` derivation');
  w();
  w('| Field | Value |');
  w('| --- | --- |');
  w('| Task | `KF-S0-API-003` |');
  w('| Source | **RBAC §3** permission matrix, transcribed in `role-permission-matrix.mjs` |');
  w('| Vocabulary | `@kf/contracts/permissions` — a transcription of API Contract §2 |');
  w(
    `| Seeded rows | **${pairs.length}** across **${perRole.filter((r) => r.count > 0).length}** roles |`,
  );
  w('| Generated by | `node apps/api/prisma/seed-data/render-derivation.mjs` |');
  w();
  w('GENERATED FILE — do not edit. It is rendered from the same module the seed');
  w('reads, so the table and the database cannot drift apart. The contracts test');
  w('asserts it is current.');
  w();
  w('---');
  w();
  w('## Rules applied');
  w();
  w('| Rule | Consequence |');
  w('| --- | --- |');
  w(
    '| Scope is not part of this table (RBAC §2.3) | The superscripts ᵀ ᴮ ᶜ ᴼ are kept in the `raw` cell for review and appear in no row. Scope resolves from `user_roles` (Domain row 14, M-003). |',
  );
  w(
    '| SUPER_ADMIN is break-glass only (RBAC §3 header) | Its tenant-data cells are **not** seeded — a row here is a standing grant. It appears only on platform-plane rows. Founder decision, 2026-09-06. |',
  );
  w(
    '| The vocabulary is the contract, not the matrix | A matrix letter with no API Contract §2 endpoint has no code to grant. Those cells are listed below, not invented. |',
  );
  w(
    '| Letter → action | C→create · R→read · U→update · D→delete · A→approve · E→export · Rs→restore · Ar→archive |',
  );
  w();
  w('## Rows per role');
  w();
  w('| Role | Seeded permissions |');
  w('| --- | --- |');
  for (const { role, count } of perRole) {
    w(`| \`${role}\` | ${count} |`);
  }
  w();
  w("`SUPER_ADMIN`'s count is small on purpose: it holds the platform plane and");
  w('nothing else until a break-glass grant is active.');
  w();
  w('---');
  w();
  w('## Matrix cell → seeded rows');
  w();
  w('| RBAC §3 row | Token(s) | Role | Cell as written in §3 | Codes seeded |');
  w('| --- | --- | --- | --- | --- |');
  for (const entry of MATRIX) {
    const tokens = entry.tokens.length > 0 ? entry.tokens.map((t) => `\`${t}\``).join(', ') : '—';
    for (const [role, c] of Object.entries(entry.cells)) {
      const codes = pairs
        .filter((p) => p.role === role && p.row === entry.row)
        .map((p) => `\`${p.code}\``);
      w(
        `| ${entry.row} | ${tokens} | \`${role}\` | ${c.raw.replace(/\|/g, '\\|')} | ${
          codes.length > 0 ? codes.join(' · ') : '—'
        } |`,
      );
    }
  }
  w();
  w('---');
  w();
  w('## Cells that decoded to no code');
  w();
  w('Each of these is a capability the RBAC matrix grants a role and the API does');
  w('not expose. None is seeded. Registered as **DISC-015** (residue) and');
  w('**DISC-023** (matrix letters with no endpoint at all).');
  w();
  w('| RBAC §3 row | Role | Code it would need | Why it is absent |');
  w('| --- | --- | --- | --- |');
  for (const u of unmapped) {
    w(`| ${u.row} | \`${u.role}\` | \`${u.code}\` | ${u.reason} |`);
  }
  w();
  w('## Contract codes with zero grants');
  w();
  w('A permission row with no `role_permissions` row is the correct, registered');
  w('outcome — the code exists because an endpoint exists, and the matrix gives it');
  w('to nobody. Do **not** invent a grant to tidy this up, and do not drop the');
  w('permission.');
  w();
  w('| Code | Why nobody holds it |');
  w('| --- | --- |');
  w(
    '| `activity:delete` | §2.7 `DELETE /activity-entries/{id}` carries `activity:update/delete`, but the §3 *Activity entries* row holds only `C R U` — no role holds `D`. The reverse discrepancy recorded in DISC-015. |',
  );
  w(
    '| `role:read` | §2.4 `GET /roles` carries `role:read`, and RBAC §3 has **no row for roles at all** — it is reference data the matrix forgot. So the endpoint that lists roles is callable by nobody, including the OWNER who assigns them. Newly found here; registered with DISC-023. |',
  );
  w();
  if (ungranted.length !== 2) {
    w(
      `> **This list is stale.** The renderer found ${ungranted.length} ungranted codes: ${ungranted
        .map((c) => `\`${c}\``)
        .join(', ')}. Update the prose above.`,
    );
    w();
  }
  w('---');
  w();
  w(
    `_${pairs.length} rows · ${unmapped.length} unmapped cells · ${ungranted.length} ungranted codes._`,
  );
  w();

  return lines.join('\n');
}

const body = render();

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== body) {
    console.error('role-permissions derivation table is STALE. Run:');
    console.error('  node apps/api/prisma/seed-data/render-derivation.mjs');
    process.exit(1);
  }
  console.log('role-permissions derivation table is up to date.');
} else {
  fs.writeFileSync(OUT, body);
  console.log(`wrote ${path.relative(process.cwd(), OUT).split(path.sep).join('/')}`);
}
