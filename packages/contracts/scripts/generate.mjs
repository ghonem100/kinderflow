#!/usr/bin/env node
/* global console, URL */
/**
 * Contract codegen — OpenAPI 3.1 → TypeScript types (KF-S0-CONTRACT-001).
 *
 * The spec is AUTHORED, the types are GENERATED. That direction is the whole
 * point of a spec-first contract (API Contract §8): a type hand-edited to
 * match an implementation would quietly make the implementation the source of
 * truth, which is the failure this package exists to prevent.
 *
 * Usage:
 *   node scripts/generate.mjs           write src/generated/api-types.ts
 *   node scripts/generate.mjs --check   fail if the committed file is stale
 *
 * `--check` is the CI drift gate (task Implementation Requirement 6). It
 * regenerates in memory and compares; it never writes. A PR that edits
 * `openapi.yaml` without regenerating fails there rather than shipping types
 * that describe a different API from the spec beside them.
 *
 * The external `$ref` split of §8 needs no bundler: openapi-typescript resolves
 * `paths/*.yaml` and `components/**` itself. Nothing beyond the two
 * dependencies Sprint 0 Guide §6 authorizes is installed.
 *
 * Exit codes: 0 written / up to date · 1 stale (--check) · 2 generation failed.
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

import { readOperations } from './spec-reader.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, '..');
const SPEC = path.join(pkgRoot, 'openapi.yaml');
const OUT = path.join(pkgRoot, 'src', 'generated', 'api-types.ts');
const OPS_OUT = path.join(pkgRoot, 'src', 'generated', 'operations.ts');

const BANNER = `/**
 * GENERATED by scripts/generate.mjs from openapi.yaml — do not edit.
 *
 * Regenerate:  pnpm --filter @kf/contracts generate
 * Verify:      pnpm --filter @kf/contracts generate:check
 */
`;

async function render() {
  const ast = await openapiTS(new URL('file://' + SPEC.split(path.sep).join('/')), {
    // The spec says every property is explicitly required, optional or
    // nullable (§3.1), so an absent property is a real signal, not noise.
    emptyObjectsUnknown: true,
  });
  return BANNER + astToString(ast);
}

/**
 * The operation manifest: every operation's id and its four `x-` extensions,
 * as data.
 *
 * openapi-typescript drops unknown extensions, so `x-permission-code` survives
 * nowhere in `api-types.ts` — and it is the single most important thing in the
 * spec, because it is what binds an endpoint to the authorization vocabulary.
 * KF-S0-API-001 diffs its decorators against this file; the contracts test
 * asserts every entry's code exists in `permissions.ts`.
 */
function renderOperations() {
  const operations = readOperations(path.join(pkgRoot, 'paths'));
  const rows = operations
    .map((op) =>
      [
        '  {',
        `    operationId: '${op.operationId}',`,
        `    method: '${op.method}',`,
        `    permissionCode: '${op.permissionCode}',`,
        `    rateLimitTier: '${op.rateLimitTier}',`,
        `    auditEvents: [${(op.auditEvents ?? []).map((e) => `'${e}'`).join(', ')}],`,
        `    idempotency: '${op.idempotency}',`,
        '  },',
      ].join('\n'),
    )
    .join('\n');

  return `${BANNER}
/** One operation's contract metadata, read from \`paths/*.yaml\`. */
export interface OperationContract {
  readonly operationId: string;
  readonly method: string;
  /** A code from \`permissions.ts\`, or the sentinel \`public\` / \`authenticated\`. */
  readonly permissionCode: string;
  readonly rateLimitTier: string;
  readonly auditEvents: readonly string[];
  readonly idempotency: string;
}

/** Every operation in the spec. Sorted by operation id. */
export const OPERATIONS: readonly OperationContract[] = [
${rows}
] as const;
`;
}

async function main() {
  const check = process.argv.includes('--check');

  let types;
  let operations;
  try {
    types = await render();
    operations = renderOperations();
  } catch (error) {
    console.error('contracts: OpenAPI generation failed.');
    console.error(String(error?.message ?? error));
    process.exit(2);
  }

  const artifacts = [
    { file: OUT, content: types, label: 'API types' },
    { file: OPS_OUT, content: operations, label: 'operation manifest' },
  ];

  if (check) {
    const stale = artifacts.filter(
      ({ file, content }) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '') !== content,
    );
    if (stale.length > 0) {
      console.error('contracts: generated output is STALE:');
      for (const { file, label } of stale) {
        console.error(`  ${label} — ${path.relative(pkgRoot, file).split(path.sep).join('/')}`);
      }
      console.error('  The spec changed without regenerating. Run:');
      console.error('    pnpm --filter @kf/contracts generate');
      process.exit(1);
    }
    console.log(`contracts: generated output is up to date (${artifacts.length} artifacts).`);
    return;
  }

  for (const { file, content } of artifacts) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    console.log(`contracts: wrote ${path.relative(pkgRoot, file).split(path.sep).join('/')}`);
  }
}

await main();
